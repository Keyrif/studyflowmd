function translateText(text) {
  if (currentLang !== 'ro') return Object.hasOwn(I18N_EN, text) ? I18N_EN[text] : text;
  if (Object.hasOwn(I18N_RO, text)) return I18N_RO[text];
  for (const [pattern, build] of I18N_RO_PATTERNS) {
    const match = text.match(pattern);
    if (match) return build(match);
  }
  return text;
}

function translateKeepingSpaces(text) {
  const match = text.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match[2]) return text;
  return match[1] + translateText(match[2]) + match[3];
}

const I18N_SKIP = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'PRE', 'CODE']);
const I18N_ATTRIBUTES = ['placeholder', 'aria-label', 'title'];
const textSources = new WeakMap();
const scrambling = new WeakMap();
const attributeSources = new WeakMap();

function isTranslatable(element) {
  return !!element && !I18N_SKIP.has(element.tagName) && !element.closest('[translate="no"]');
}

function translateTextNode(node) {
  if (!isTranslatable(node.parentElement)) return;
  const frame = scrambling.get(node);
  if (frame !== undefined) {
    if (node.nodeValue === frame) return;
    scrambling.delete(node);
  }
  const current = node.nodeValue;
  let entry = textSources.get(node);
  if (!entry || current !== entry.output) entry = { source: current };
  entry.output = translateKeepingSpaces(entry.source);
  textSources.set(node, entry);
  if (entry.output !== current) node.nodeValue = entry.output;
}

function translateAttribute(element, name) {
  if (!element.hasAttribute(name) || !isTranslatable(element)) return;
  const current = element.getAttribute(name);
  const entries = attributeSources.get(element) || {};
  let entry = entries[name];
  if (!entry || current !== entry.output) entry = { source: current };
  entry.output = translateText(entry.source);
  entries[name] = entry;
  attributeSources.set(element, entries);
  if (entry.output !== current) element.setAttribute(name, entry.output);
}

function translateTree(root) {
  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root);
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  I18N_ATTRIBUTES.forEach((name) => translateAttribute(root, name));
  root.querySelectorAll('*').forEach((element) => {
    I18N_ATTRIBUTES.forEach((name) => translateAttribute(element, name));
  });
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) translateTextNode(walker.currentNode);
}

new MutationObserver((mutations) => {
  for (const mutation of mutations) {
    if (mutation.type === 'characterData') translateTextNode(mutation.target);
    else if (mutation.type === 'attributes') translateAttribute(mutation.target, mutation.attributeName);
    else mutation.addedNodes.forEach(translateTree);
  }
}).observe(document.documentElement, {
  subtree: true,
  childList: true,
  characterData: true,
  attributes: true,
  attributeFilter: I18N_ATTRIBUTES,
});

